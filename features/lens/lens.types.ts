/**
 * Lens dashboard contract as Crawllex uses it. The SEO part is served by the Lens API
 * (`GET /v1/projects/:id/seo`, crawllex-lens `src/api/lens-view.ts`). Rule text, grouping and
 * severity come from the Lens rule catalog (crawllex-lens `src/seo/catalog.ts`); do not add rule text here.
 * Uptime and incidents are still demo data (see lens.demo.ts) until the uptime phase.
 */

export type TLensSeverity = "high" | "medium" | "advisory";
/** Rule type from the catalog: on-page or technical. */
export type TLensGroup = "onpage" | "technical";

export type TLensRuleGroup =
  | "titles"
  | "descriptions"
  | "headings"
  | "content"
  | "images"
  | "indexing"
  | "robots"
  | "urls"
  | "links"
  | "structured";

export type TLensBand = "needs_attention" | "needs_work" | "healthy";
export type TLensCoverageReason = "none" | "cap_reached" | "gaps";
export type TLensRuleResult = "pass" | "finding" | "not_evaluated";
export type TLensPageState = "checked" | "failed" | "not_evaluated";

/** Lifecycle event codes written by Lens (issue_events.event). Labels are translated in the UI. */
export type TLensEventCode =
  | "opened"
  | "seen"
  | "reopened"
  | "resolved"
  | "fix_failed"
  | "verified"
  | "not_seen_partial"
  | "verification_inconclusive";

export type TLensIssue = {
  /** Rule code, for example missing_title. One issue per rule. */
  id: string;
  title: string;
  severity: TLensSeverity;
  group: TLensGroup;
  ruleGroup: TLensRuleGroup;
  status: "open" | "resolved";
  resolvedOn: string | null;
  /** Open pages affected by this rule. */
  affected: number;
  found: string;
  why: string;
  fix: string;
  verify: string;
  /** Not generated by Lens yet. Null until an AI suggestion source exists. */
  aiSuggestion: string | null;
  tracking: { firstSeen: string; events: { date: string; event: TLensEventCode }[] };
  /** Page URLs with this issue open. */
  pages: string[];
};

export type TLensRuleCheck = {
  id: string;
  title: string;
  severity: TLensSeverity;
  result: TLensRuleResult;
};

export type TLensPage = {
  url: string;
  finalUrl: string | null;
  /** Meta title as fetched. Null when the page has no title. */
  metaTitle: string | null;
  state: TLensPageState;
  httpStatus: number | null;
  errorCode: string | null;
  counts: { mustFix: number; shouldFix: number; worthALook: number };
  ruleChecks: TLensRuleCheck[];
};

export type TLensRun = {
  id: string;
  status: "completed" | "failed" | "running";
  coverage: "complete" | "partial" | null;
  coverageReason: TLensCoverageReason | null;
  startedAt: string;
  finishedAt: string | null;
  pagesChecked: number;
  knownUrls: number | null;
  score: number | null;
  newIssues: number | null;
  resolvedIssues: number | null;
  openIssues: number | null;
  errorCode: string | null;
};

export type TLensSeo = {
  score: number | null;
  band: TLensBand | null;
  scoreModel: string | null;
  coverage: "complete" | "partial" | null;
  coverageReason: TLensCoverageReason | null;
  checked: number;
  known: number;
  partial: boolean;
  pagesAffected: number;
  /** Open high-severity (Must Fix) rules. */
  failed: number;
  /** Open medium-severity (Should Fix) rules. */
  warnings: number;
  /** Open advisory (Worth a Look) rules. */
  notices: number;
  bySeverity: Record<TLensSeverity, number>;
};

export type TLensSeoDashboard = {
  siteUrl: string;
  lastCheckAt: string | null;
  latestRunId: string | null;
  seo: TLensSeo;
  issues: TLensIssue[];
  pages: TLensPage[];
  runs: TLensRun[];
};

export type TLensUptimeDay = { day: string; uptimePct: number | null };

export type TLensUptime = {
  status: "operational" | "down" | "unknown";
  percent: number;
  totalDowntimeMin: number;
  incidents: number;
  avgResponseMs: number;
  p95ResponseMs: number;
  lastCheckedAt: string;
  lastSuccessAt: string;
  daily: TLensUptimeDay[];
  checks: number;
};

export type TLensIncident = {
  id: string;
  startedAt: string;
  durationMin: number;
  status: "resolved" | "ongoing";
  reason: string;
  detected: string;
  recovered: string | null;
};

/** Everything the Lens page renders. */
export type TLensDashboard = TLensSeoDashboard & {
  uptime: TLensUptime;
  incidents: TLensIncident[];
};
